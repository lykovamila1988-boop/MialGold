def get_deep_content_examples(content_type="all"):
    """Получить примеры глубокого контента для промптов"""
    if content_type == "insights":
        return DEEP_INSIGHTS
    elif content_type == "cases":
        return DEEP_CASES
    elif content_type == "practices":
        return DEEP_PRACTICES
    else:
        return {
            "insights": DEEP_INSIGHTS,
            "cases": DEEP_CASES,
            "practices": DEEP_PRACTICES
        }

